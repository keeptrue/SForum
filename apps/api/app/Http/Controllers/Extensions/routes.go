package extensionscontroller

import "github.com/gofiber/fiber/v3"

func (h *Controller) RegisterRoutes(api fiber.Router) {
	// 前台：当前激活主题的非 secret 设置（主题 layer 消费）。
	api.Get("/site/active-theme/settings", h.publicActiveThemeSettings)
	// page-policy / *-catalog 必须在带 :extensionId 的 runtime 路由之前注册，避免被 path 参数吞掉。
	api.Get("/extensions/runtime/page-policy", h.publicFrontendPagePolicy)
	api.Get("/extensions/runtime/content-styles", h.publicContentStyles)
	api.Get("/extensions/runtime/editor-catalog", h.publicEditorCatalog)
	api.Get("/extensions/runtime/entity-catalog", h.publicEntityCatalog)
	api.Get("/extensions/runtime/content-catalog", h.publicContentCatalog)
	api.Get("/extensions/runtime/media-catalog", h.publicMediaCatalog)
	api.Get("/extensions/runtime/:extensionId/components/:componentId", h.publicFrontendComponent)
	api.Get("/extensions/runtime/:extensionId/assets/:packageDigest/:digest/:handle", h.publicFrontendAsset)
	api.Get("/extensions/runtime/:extensionId/packages/:packageDigest/*", h.publicFrontendPackageAsset)

	api.Get("/admin/admin-surfaces", h.listAdminSurfaces)
	api.Post("/admin/admin-surfaces/:surfaceId/invoke", h.invokeAdminSurface)
	// entity import/export dry-run：在带 :id 的 extension 路由之前注册。
	api.Get("/admin/extensions/entity-catalog/:entityId/import-export-dry-run", h.entityImportExportDryRun)
	api.Get("/admin/extensions", h.list)
	api.Get("/admin/extensions/navigation", h.navigation)
	api.Get("/admin/extensions/contribution-points", h.contributionPoints)
	api.Get("/admin/extensions/contributions", h.contributions)
	// 设置面治理：站点设置页插件 tab + 贡献覆盖（enabled / sortOrder）。
	api.Get("/admin/settings/surface-tabs", h.surfaceTabs)
	api.Put("/admin/extensions/contributions/:point/:contributionId", h.updateContributionGovernance)
	api.Delete("/admin/extensions/contributions/:point/:contributionId", h.resetContributionGovernance)
	api.Put("/admin/extensions/contributions/:point/:contributionId/items/:itemKey", h.updateContributionItemGovernance)
	api.Delete("/admin/extensions/contributions/:point/:contributionId/items/:itemKey", h.resetContributionItemGovernance)
	api.Get("/admin/extensions/route-providers/conflicts", h.routeProviderConflicts)
	api.Get("/admin/extensions/route-providers/selection", h.routeProviderCurrent)
	api.Get("/admin/extensions/route-providers/events", h.routeProviderEvents)
	api.Get("/admin/extensions/cache-inspector", h.inspectCache)
	api.Get("/admin/extensions/asset-inspector", h.inspectAsset)
	api.Get("/admin/extensions/template-inspector", h.inspectTemplates)
	api.Get("/admin/extensions/component-inspector", h.inspectComponentComposition)
	api.Get("/admin/extensions/navigation-inspector", h.inspectNavigation)
	api.Get("/admin/extensions/route-inspector", h.inspectRoute)
	api.Get("/admin/extensions/route-catalog", h.routeCatalog)
	api.Get("/admin/extensions/query-catalog", h.queryCatalog)
	api.Get("/admin/extensions/route-incidents", h.inspectRouteIncidents)
	api.Get("/admin/extensions/openapi/aggregate", h.routeOpenAPIAggregate)
	api.Get("/admin/extensions/openapi/generated-client", h.routeGeneratedClientMetadata)
	api.Post("/admin/extensions/route-providers/selection", h.selectRouteProvider)
	api.Post("/admin/extensions/route-providers/selection/reset", h.resetRouteProvider)
	api.Get("/admin/extensions/provider-slots", h.inspectProviderSlots)
	api.Get("/admin/extensions/provider-slots/events", h.providerSlotEvents)
	api.Post("/admin/extensions/provider-slots/selection", h.selectProviderSlot)
	api.Post("/admin/extensions/provider-slots/selection/reset", h.resetProviderSlot)
	api.Post("/admin/extensions/provider-slots/probe", h.probeProviderSlot)
	api.Post("/admin/extensions", h.install)
	api.Post("/admin/extensions/install-from-url", h.installFromURL)
	api.Post("/admin/extensions/missing-artifacts/uninstall", h.cleanupMissingArtifacts)
	// 卸载清理免键收尾：原幂等键丢失时由 super_admin 按扩展收敛 pending tombstone。
	api.Post("/admin/extensions/:id/uninstall-cleanup/finalize", h.finalizeUninstallCleanup)
	// 版本 GC（阶段 5）：静态段必须在带 :id 的 extension 路由之前注册。
	// GET 走 extensions read 粗门 + 服务层 super_admin 权威策略；
	// POST 走 super_admin 守卫 + 服务层同款权威策略。
	api.Get("/admin/extensions/version-gc/candidates", h.versionGcCandidates)
	api.Post("/admin/extensions/version-gc/confirmations", h.createVersionGcConfirmation)
	api.Post("/admin/extensions/version-gc/execute", h.executeVersionGcSweep)
	api.Delete("/admin/extensions/:id", h.uninstall)
	api.Post("/admin/extensions/:id/enable", h.enable)
	api.Post("/admin/extensions/:id/restart", h.restart)
	api.Get("/admin/extensions/:id/trust", h.executableTrustStatus)
	api.Post("/admin/extensions/:id/trust/challenge", h.issueExecutableTrustChallenge)
	api.Delete("/admin/extensions/:id/trust", h.revokeExecutableTrust)
	api.Post("/admin/extensions/:id/disable", h.disable)
	api.Post("/admin/extensions/:id/upgrade", h.upgrade)
	api.Post("/admin/extensions/:id/rollback", h.rollback)
	api.Post("/admin/extensions/:id/verify", h.verify)
	api.Post("/admin/extensions/:id/activate", h.activate)
	api.Get("/admin/extensions/:id/events", h.events)
	api.Get("/admin/extensions/:id/lifecycle", h.lifecycleOperations)
	api.Get("/admin/extensions/:id/lifecycle/:operationID", h.lifecycleOperation)
	api.Post("/admin/extensions/:id/lifecycle/:operationID/recovery", h.recoverLifecycleOperation)
	api.Get("/admin/extensions/:id/migrations", h.listMigrations)
	api.Post("/admin/extensions/:id/migrations/apply", h.applyMigrations)
	api.Get("/admin/extensions/:id/page-bootstrap", h.pageBootstrap)
	api.Get("/admin/extensions/:id/settings", h.settings)
	api.Put("/admin/extensions/:id/settings", h.updateSettings)
	api.Post("/admin/extensions/:id/settings/reset", h.resetSettings)
	api.Post("/admin/extensions/:id/settings/actions/:actionId", h.executeSettingsAction)
	api.Get("/admin/extensions/:id/frontend", h.frontendStatus)
	api.Get("/admin/extensions/:id/frontend/assets/:digest/:component/:asset", h.frontendComponentAsset)
	api.Get("/admin/extensions/:id/frontend/assets/:digest/:asset", h.frontendAsset)
	api.Post("/admin/extensions/:id/frontend/confirmation", h.frontendConfirmation)
	api.Post("/admin/extensions/:id/frontend/trust", h.grantFrontendTrust)
	api.Delete("/admin/extensions/:id/frontend/trust", h.revokeFrontendTrust)
	api.Get("/admin/extensions/event-definitions", h.eventDefinitions)
	api.Get("/admin/extensions/event-deliveries", h.eventDeliveries)
	api.Post("/admin/extensions/dev-trust-sessions", h.createDevTrustSession)
	api.Get("/admin/extensions/dev-trust-sessions", h.listDevTrustSessions)
	api.Delete("/admin/extensions/dev-trust-sessions/:id", h.revokeDevTrustSession)
	api.Post("/admin/extensions/:id/dev-trust-refresh", h.devTrustRefresh)

	api.All("/extensions/:extensionId/*", h.proxyExtensionRoute)
}
