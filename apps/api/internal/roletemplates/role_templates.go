// Package roletemplates 把 Identity/seeds.go 的角色模板渲染成 web 端生成物。
//
// 为什么要有这个包：`apps/web/app/config/roleTemplates.ts` 曾经是一份手写副本，
// 于是「后台应用模板给新角色预填的权限」与「迁移真正写进库的权限」会各自漂移
// （模板给多了 = 新建组凭空多权限，模板给少了 = 新建组缺权限但没人发现）。
// 现在唯一权威源是 Identity/seeds.go 的 SeedRoleTemplates，这个包只负责渲染，
// cmd/sforum 的 roles:templates 负责写盘/校验，生成物一致性由包内测试守护。
package roletemplates

import (
	"strings"

	"github.com/keeptrue/sforum/apps/api/app/Models/Identity"
)

// DefaultOutput 是生成物相对 repo root 的路径。
const DefaultOutput = "apps/web/app/config/roleTemplates.ts"

// header 是生成物首行：指向唯一权威源与重生成命令，并明确禁止手改。
const header = "// Code generated by `cd apps/api && go run ./cmd/sforum roles:templates --write`. DO NOT EDIT."

// preamble 是生成物顶部的说明块（不含任何行号引用，避免 seeds.go 变动后失效）。
const preamble = `/**
 * 内置角色模板权限包：**生成物**，不要手改。
 * 唯一权威源是 apps/api/app/Models/Identity/seeds.go 的 SeedRoleTemplates；
 * 后台「应用模板」在创建自定义组时预填这里的权限，系统模板角色本身由迁移 seed。
 *
 * 重新生成：cd apps/api && go run ./cmd/sforum roles:templates --write
 * 校验：cd apps/api && go run ./cmd/sforum roles:templates --check
 */`

// typeDecl 是 web 侧消费的类型契约，字段语义随生成物一起固定。
const typeDecl = `export type RoleTemplateDefinition = {
  key: string
  /** i18n：admin.roleCatalog.<key>.alias */
  aliasKey: string
  /** i18n：admin.roleCatalog.<key>.description */
  descriptionKey: string
  permissionKeys: readonly string[]
}`

// tailDecl 是生成物结尾的查询辅助与类型收口。
const tailDecl = `export function findRoleTemplate(key: string): RoleTemplateDefinition | undefined {
  return ROLE_TEMPLATE_DEFINITIONS.find(template => template.key === key)
}`

// Current 返回当前 seeds 的渲染结果。
//
// 刻意不做 IO：seeds 就是唯一权威源，渲染不需要读磁盘。
func Current() string {
	return Render(identity.SeedRoleTemplates)
}

// Render 把模板渲染成 TS 生成物。输出只由入参决定（同输入必得同字节），
// 权限键顺序与 seeds 完全一致——顺序变了就是 diff，评审能看见。
func Render(templates []identity.SeedRoleTemplate) string {
	var b strings.Builder
	b.WriteString(header)
	b.WriteString("\n\n")
	b.WriteString(preamble)
	b.WriteString("\n\n")
	b.WriteString(typeDecl)
	b.WriteString("\n\nexport const ROLE_TEMPLATE_DEFINITIONS = [\n")

	for i, template := range templates {
		b.WriteString("  {\n")
		b.WriteString("    key: '" + quoteTS(template.Key) + "',\n")
		b.WriteString("    aliasKey: '" + aliasKey(template.Key) + "',\n")
		b.WriteString("    descriptionKey: '" + descriptionKey(template.Key) + "',\n")
		b.WriteString("    permissionKeys: [\n")
		for j, permission := range template.PermissionKeys {
			b.WriteString("      '" + quoteTS(permission) + "'")
			if j < len(template.PermissionKeys)-1 {
				b.WriteString(",")
			}
			b.WriteString("\n")
		}
		b.WriteString("    ]\n")
		b.WriteString("  }")
		if i < len(templates)-1 {
			b.WriteString(",")
		}
		b.WriteString("\n")
	}

	b.WriteString("] as const satisfies readonly RoleTemplateDefinition[]\n\n")
	b.WriteString(tailDecl)
	b.WriteString("\n")
	return b.String()
}

// aliasKey / descriptionKey 固定 i18n 命名规则：<前缀>.<角色 key>.<字段>。
func aliasKey(roleKey string) string {
	return "admin.roleCatalog." + roleKey + ".alias"
}

func descriptionKey(roleKey string) string {
	return "admin.roleCatalog." + roleKey + ".description"
}

// quoteTS 让单引号字符串在 TS 里安全：反斜杠与单引号转义，换行不可能出现（键是常量）。
func quoteTS(value string) string {
	return strings.NewReplacer(`\`, `\\`, `'`, `\'`).Replace(value)
}
