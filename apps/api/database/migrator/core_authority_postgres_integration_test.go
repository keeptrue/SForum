func assertCoreAuthorityMembership(t *testing.T, ctx context.Context, db *sql.DB, fixture *coreAuthorityTestDatabase) {
	t.Helper()
	var adminOption, inheritOption, setOption bool
	if err := db.QueryRowContext(ctx, `
		SELECT COALESCE(bool_or(memberships.admin_option), FALSE),
		       COALESCE(bool_or(memberships.inherit_option), FALSE),
		       COALESCE(bool_or(memberships.set_option), FALSE)
		FROM pg_auth_members AS memberships
		JOIN pg_roles AS granted ON granted.oid = memberships.roleid
		JOIN pg_roles AS member ON member.oid = memberships.member
		WHERE granted.rolname = $1 AND member.rolname = $2
	`, fixture.ownerRole, fixture.sessionRole).Scan(&adminOption, &inheritOption, &setOption); err != nil {
		t.Fatal(err)
	}
	if !adminOption || !inheritOption || !setOption {
		t.Fatalf("Core owner membership options = %t/%t/%t", adminOption, inheritOption, setOption)
	}
}

func assertCoreAuthorityCreatorMembership(
	t *testing.T,
	ctx context.Context,
	db *sql.DB,
	fixture *coreAuthorityTestDatabase,
) int {
	t.Helper()
	var rows, creatorAdminRows, selfGrantedAuthorityRows int
	var adminOption, inheritOption, setOption, canSet, hasPrivileges bool
	if err := db.QueryRowContext(ctx, `
		SELECT count(*),
		       count(*) FILTER (
		         WHERE memberships.admin_option
		           AND NOT memberships.inherit_option AND NOT memberships.set_option
		       ),
		       count(*) FILTER (
		         WHERE NOT memberships.admin_option
		           AND memberships.inherit_option AND memberships.set_option
		       ),
		       COALESCE(bool_or(memberships.admin_option), FALSE),
		       COALESCE(bool_or(memberships.inherit_option), FALSE),
		       COALESCE(bool_or(memberships.set_option), FALSE),
		       pg_has_role($2, $1, 'SET'), pg_has_role($2, $1, 'USAGE')
		FROM pg_auth_members AS memberships
		JOIN pg_roles AS granted ON granted.oid = memberships.roleid
		JOIN pg_roles AS member ON member.oid = memberships.member
		WHERE granted.rolname = $1 AND member.rolname = $2
	`, fixture.ownerRole, fixture.sessionRole).Scan(
		&rows, &creatorAdminRows, &selfGrantedAuthorityRows,
		&adminOption, &inheritOption, &setOption, &canSet, &hasPrivileges,
	); err != nil {
		t.Fatal(err)
	}
	if rows != 2 || creatorAdminRows != 1 || selfGrantedAuthorityRows != 1 ||
		!adminOption || !inheritOption || !setOption || !canSet || !hasPrivileges {
		t.Fatalf(
			"creator membership = rows:%d creatorAdmin:%d selfAuthority:%d admin:%t inherit:%t set:%t canSet:%t privileges:%t",
			rows, creatorAdminRows, selfGrantedAuthorityRows,
			adminOption, inheritOption, setOption, canSet, hasPrivileges,
		)
	}
	return rows
}

func assertCoreAuthorityDatabaseCreateRevoked(t *testing.T, ctx context.Context, db *sql.DB, ownerRole string) {
	t.Helper()
	var canCreate bool
	if err := db.QueryRowContext(ctx, `
		SELECT has_database_privilege($1, current_database(), 'CREATE')
	`, ownerRole).Scan(&canCreate); err != nil {
		t.Fatal(err)
	}
	if canCreate {
		t.Fatalf("Core owner %s retained database CREATE after Goose", ownerRole)
	}
}

func assertCoreAuthorityOwner(t *testing.T, ctx context.Context, db *sql.DB, objectKind string, qualifiedName string, expectedOwner string) {
	t.Helper()
	parts := strings.SplitN(qualifiedName, ".", 2)
	var query string
	var arguments []any
	switch objectKind {
	case "schema":
		query = `
			SELECT owners.rolname
			FROM pg_namespace AS namespaces
			JOIN pg_roles AS owners ON owners.oid = namespaces.nspowner
			WHERE namespaces.nspname = $1
		`
		arguments = []any{parts[0]}
	case "relation":
		query = `
			SELECT owners.rolname
			FROM pg_class AS classes
			JOIN pg_namespace AS namespaces ON namespaces.oid = classes.relnamespace
			JOIN pg_roles AS owners ON owners.oid = classes.relowner
			WHERE namespaces.nspname = $1 AND classes.relname = $2
		`
		arguments = []any{parts[0], parts[1]}
	case "routine":
		query = `
			SELECT owners.rolname
			FROM pg_proc AS routines
			JOIN pg_namespace AS namespaces ON namespaces.oid = routines.pronamespace
			JOIN pg_roles AS owners ON owners.oid = routines.proowner
			WHERE namespaces.nspname = $1 AND routines.proname = $2
		`
		arguments = []any{parts[0], parts[1]}
	case "type":
		query = `
			SELECT owners.rolname
			FROM pg_type AS types
			JOIN pg_namespace AS namespaces ON namespaces.oid = types.typnamespace
			JOIN pg_roles AS owners ON owners.oid = types.typowner
			WHERE namespaces.nspname = $1 AND types.typname = $2
		`
		arguments = []any{parts[0], parts[1]}
	case "extension":
		query = `
			SELECT owners.rolname
			FROM pg_extension AS extensions
			JOIN pg_roles AS owners ON owners.oid = extensions.extowner
			WHERE extensions.extname = $1
		`
		arguments = []any{parts[0]}
	default:
		t.Fatalf("unknown Core authority object kind %q", objectKind)
	}
	var actualOwner string
	if err := db.QueryRowContext(ctx, query, arguments...).Scan(&actualOwner); err != nil {
		t.Fatalf("inspect %s %s owner: %v", objectKind, qualifiedName, err)
	}
	if actualOwner != expectedOwner {
		t.Fatalf("%s %s owner = %s, want %s", objectKind, qualifiedName, actualOwner, expectedOwner)
	}
}
