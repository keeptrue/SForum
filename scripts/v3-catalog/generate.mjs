function read(path) {
  return readFileSync(resolve(root, path), 'utf8')
}

function walk(path, suffix) {
  const absolute = resolve(root, path)
  const result = []
  for (const name of readdirSync(absolute)) {
    const child = join(absolute, name)
    if (statSync(child).isDirectory()) result.push(...walk(relative(root, child), suffix))
    else if (!suffix || child.endsWith(suffix)) result.push(relative(root, child))
  }
  return result.sort()
}

function put(path, content) {
  outputs.set(path, content.endsWith('\n') ? content : `${content}\n`)
}

function json(path, value) {
  put(path, `${JSON.stringify(value, null, 2)}\n`)
}

function cell(value) {
  return String(value ?? '').replaceAll('|', '\\|').replaceAll('\n', ' ')
}

function parseAuthoritativeRows() {
  const source = read('knowledge/decisions/2026-07-13-trusted-plugin-theme-platform-v3.md')
  const sections = [
    ['theme', '### Template And Theme Mechanism Comparison', '### Plugin Mechanism Comparison'],
    ['plugin', '### Plugin Mechanism Comparison', '## Architecture Mind Map']
  ]
  const rows = []
  for (const [family, startMarker, endMarker] of sections) {
    const start = source.indexOf(startMarker)
    const end = source.indexOf(endMarker, start + startMarker.length)
    if (start < 0 || end < 0) throw new Error(`cannot find ADR table: ${family}`)
    const lines = source.slice(start, end).split('\n').filter(line => line.startsWith('| '))
    for (const line of lines.slice(2)) {
      const columns = line.split('|').slice(1, -1).map(item => item.trim())
      if (columns.length !== 3) throw new Error(`invalid ${family} table row: ${line}`)
      rows.push({ family, surface: columns[0], current: columns[1], target: columns[2] })
    }
  }
  if (rows.length !== 99) throw new Error(`ADR must contain 99 authoritative rows, found ${rows.length}`)
  return rows
}

function renderTraceability(rows) {
  const lines = [
    '# Trusted Plugin And Theme Platform V3 Traceability Matrix',
    '',
    '<!-- Generated by scripts/v3-catalog/generate.mjs. Do not edit by hand. -->',
    '',
    'This matrix maps all 27 theme rows and 72 plugin rows from the accepted V3 ADR.',
    'A row remains incomplete until its named test exists and the phase exit gate passes.',
    '',
    '| # | Family | Surface | Current | V3 target | Phase | Contract | Test ID | Rollback |',
    '| ---: | --- | --- | --- | --- | --- | --- | --- | --- |'
  ]
  for (const row of rows) {
    lines.push(`| ${row.row} | ${cell(row.family)} | ${cell(row.surface)} | ${cell(row.current)} | ${cell(row.target)} | ${row.phase} | ${cell(row.contract)} | \`${row.test}\` | ${cell(row.rollback)} |`)
  }
  lines.push('')
  return lines.join('\n')
}

function normalizePath(...parts) {
  const value = parts.join('/').replaceAll(/\/+/g, '/')
  return value === '/' ? value : value.replace(/\/$/, '')
}

function snake(value) {
  return value
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/[^A-Za-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .toLowerCase()
}

function routeRegistrationSource(source, receiver, method, path) {
  const needle = `${receiver}.${method}(${JSON.stringify(path)}`
  const lines = read(source).split('\n')
  const matches = lines.flatMap((line, index) => line.includes(needle) ? [index + 1] : [])
  if (matches.length !== 1) {
    throw new Error(`expected exactly one route registration ${needle} in ${source}, found ${matches.length}`)
  }
  return `${source}:${matches[0]}`
}

