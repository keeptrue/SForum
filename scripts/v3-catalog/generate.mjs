function renderMatrix(matrix) {
  const lines = ['# Extension Surface Matrix', '', '<!-- Generated by scripts/v3-catalog/generate.mjs. -->', '', 'Every module must keep all eleven families explicit. `closed` requires a reason; `planned` names its delivery phase.', '', `| Module | ${matrixFamilies.join(' | ')} |`, `| --- | ${matrixFamilies.map(() => '---').join(' | ')} |`]
  for (const [module, values] of Object.entries(matrix)) {
    const cells = matrixFamilies.map(family => {
      const value = values[family]
      if (value.state === 'closed') return `closed: ${value.reason}`
      return `${value.state} ${value.phase}: ${value.contract || 'contract pending'}`
    })
    lines.push(`| ${module} | ${cells.map(cell).join(' | ')} |`)
  }
  return `${lines.join('\n')}\n`
}

