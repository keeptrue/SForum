function reviewedRouteGuard(route, access, policy) {
  const reviewed = reviewedGuardPolicies.get(policy)
  if (!reviewed) throw new Error(`route ${route.method} ${route.path} has no reviewed guard classification: ${access} / ${policy}`)
  return {
    kind: reviewed.kind,
    permissions: [...(reviewed.permissions || [])],
    evaluatorId: reviewed.evaluatorId || ''
  }
}

function discoverRoutes() {
  const files = walk('apps/api/app/Http/Controllers', '.go').filter(path => !path.endsWith('_test.go'))
  const routes = []
  for (const source of files) {
    const content = read(source)
    if (!content.includes('RegisterRoutes')) continue
    const module = snake(source.split('/').at(-2))
    const routers = new Map([['api', '']])
    const lines = content.split('\n')
    for (let index = 0; index < lines.length; index++) {
      const line = lines[index]
      const group = line.match(/(\w+)\s*:=\s*(\w+)\.Group\("([^"]*)"\)/)
      if (group && routers.has(group[2])) routers.set(group[1], normalizePath(routers.get(group[2]), group[3]))
      for (const match of line.matchAll(/(\w+)\.(Get|Post|Put|Patch|Delete|All)\("([^"]*)"\s*,([^)]*)\)/g)) {
        if (!routers.has(match[1])) continue
        const handlerMatch = [...match[4].matchAll(/h\.([A-Za-z0-9_]+)/g)].at(-1)
        if (!handlerMatch) continue
        const path = normalizePath('/api/v1', routers.get(match[1]), match[3])
        const method = match[2] === 'All' ? '*' : match[2].toUpperCase()
        routes.push({ module, handler: handlerMatch[1], method, path, source: `${source}:${index + 1}` })
      }
    }
  }
  routes.push(
    { module: 'system', handler: 'health', method: 'GET', path: '/api/v1/health', source: routeRegistrationSource('apps/api/app/Http/server.go', 'api', 'Get', '/health') },
    { module: 'system', handler: 'ready', method: 'GET', path: '/api/v1/ready', source: routeRegistrationSource('apps/api/app/Http/server.go', 'api', 'Get', '/ready') }
  )
  const unique = new Map()
  for (const route of routes) unique.set(`${route.method} ${route.path} ${route.handler}`, route)
  const items = [...unique.values()].sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method))
  const idCount = new Map()
  for (const item of items) idCount.set(`${item.module}.${snake(item.handler)}`, (idCount.get(`${item.module}.${snake(item.handler)}`) || 0) + 1)
  return items.map(item => {
    const base = `${item.module}.${snake(item.handler)}`
    const methodIdentity = routeMethodIdentity(item.method)
    const suffix = idCount.get(base) > 1 ? `.${methodIdentity}` : ''
    const [access, policy] = routePolicy(item)
    return {
      id: `core.route.${base}${suffix}`,
      contractVersion: `sforum.route.${base}@1`,
      ...item,
      access,
      policy,
      guard: reviewedRouteGuard(item, access, policy)
    }
  })
}

function routeFromPage(source) {
  const parts = source.replace('apps/web/app/pages/', '').replace(/\.vue$/, '').split('/')
  if (parts.at(-1) === 'index') parts.pop()
  return `/${parts.map(part => part.replace(/^\[\.\.\.(.+)\]$/, ':$1*').replace(/^\[(.+)\]$/, ':$1')).join('/')}`.replace(/\/$/, '') || '/'
}

function pageCatalogMap() {
  const source = read('apps/api/app/Support/Pages/catalog.go')
  const map = new Map()
  for (const match of source.matchAll(/ID:\s*"([^"]+)"[\s\S]*?CoreComponent:\s*"([^"]+)"/g)) {
    map.set(`apps/web/app/${match[2]}.vue`, match[1])
  }
  return map
}

// 页面区域目录：Go 的 RegionCatalog 是唯一手写来源，web 侧常量由它生成，
// 避免「后端加了区域、前端白名单没跟上」这类静默漂移。
function pageRegionCatalog() {
  const source = read('apps/api/app/Support/RegionCatalog/catalog.go')
  const constants = new Map()
  for (const match of source.matchAll(/^\s*Region([A-Za-z0-9]+)\s*=\s*"([a-z0-9_]+)"/gm)) {
    constants.set(`Region${match[1]}`, match[2])
  }
  const resolve = identifier => constants.get(`Region${identifier}`)

  const regionStart = source.indexOf('var standardRegions')
  const regionEnd = source.indexOf('// pageRegionMatrix')
  if (regionStart < 0 || regionEnd < 0) throw new Error('cannot locate RegionCatalog.standardRegions')
  const regions = []
  for (const match of source.slice(regionStart, regionEnd).matchAll(/\{ID:\s*Region([A-Za-z0-9]+),[^}]*?Kind:\s*RegionKind([A-Za-z0-9]+)/g)) {
    const id = resolve(match[1])
    if (!id) throw new Error(`RegionCatalog declares an unknown region constant: Region${match[1]}`)
    regions.push({ id, kind: match[2].toLowerCase() })
  }

  const matrixStart = source.indexOf('var pageRegionMatrix')
  const matrixEnd = source.indexOf('// StandardRegions returns')
  if (matrixStart < 0 || matrixEnd < 0) throw new Error('cannot locate RegionCatalog.pageRegionMatrix')
  const pages = []
  for (const match of source.slice(matrixStart, matrixEnd).matchAll(/"([a-z][a-z0-9._]*)"\s*:\s*\{([^}]*)\}/g)) {
    const ids = [...match[2].matchAll(/Region([A-Za-z0-9]+)/g)]
      .map(item => resolve(item[1]))
      .filter(Boolean)
    if (!ids.length) throw new Error(`RegionCatalog page ${match[1]} exposes no regions`)
    pages.push({ page: match[1], regions: ids })
  }
  if (!regions.length || !pages.length) throw new Error('RegionCatalog parsed empty')
  return { regions, pages }
}

// 公开页运行时面目录：作者视角的「这个页我能改什么」。
//
// 来源全部是既有唯一手写来源：Pages 核心目录（页面 id/path/access/contract/coreComponent）、
// RegionCatalog 的 pageRegionMatrix（区域）、theme_package.go 的 PageView 词表（正文来源）、
// 以及 template.go 的 allowedHostIslands（主题可挂的宿主岛）。
// 生成而不是手写，是因为这四张表过去各自漂移过。
function buildPublicPageSurfaceCatalog() {
  const catalogSource = read('apps/api/app/Support/Pages/catalog.go')
  const start = catalogSource.indexOf('var coreCatalog = []PageDefinition{')
  const end = catalogSource.indexOf('// pageRegionMatrix')
  if (start < 0) throw new Error('cannot locate Pages.coreCatalog')
  const body = catalogSource.slice(start, catalogSource.indexOf('\n}\n', start) + 1)
  const pages = []
  for (const line of body.split('\n')) {
    const id = line.match(/ID:\s*"([^"]+)"/)
    if (!id) continue
    const field = name => line.match(new RegExp(`${name}:\\s*"([^"]+)"`))?.[1] ?? ''
    const flag = name => new RegExp(`${name}:\\s*true`).test(line)
    const features = line.match(/RequiresFeatures:\s*\[([^\]]*)\]/)
    pages.push({
      id: id[1],
      pathPattern: field('PathPattern'),
      access: field('Access') || 'public',
      contractVersion: field('ContractVersion'),
      coreComponent: field('CoreComponent'),
      replaceable: flag('Replaceable'),
      // Virtual 页面没有路径（错误边界等），由渲染路径而非 URL 触发。
      virtual: flag('Virtual'),
      requiresFeatures: features
        ? [...features[1].matchAll(/"([^"]+)"/g)].map(item => item[1])
        : [],
      notes: field('Notes')
    })
  }
  if (!pages.length) throw new Error('Pages.CorePages parsed empty')

  const regionMatrix = pageRegionCatalog()
  const regionsByPage = new Map(regionMatrix.pages.map(item => [item.page, item.regions]))

  const viewSource = read('apps/api/app/Support/Pages/theme_package.go')
  const views = [...viewSource.matchAll(/PageView([A-Za-z]+)\s+PageView\s*=\s*"([a-z]+)"/g)]
    .map(match => match[2])
    .sort()
  if (views.length !== 3) throw new Error(`expected three page views, parsed ${JSON.stringify(views)}`)

  // Layout 常量与页面目录同在 catalog.go（theme_package.go 只引用它们）。
  const layouts = [...catalogSource.matchAll(/Layout([A-Za-z]+)\s+PageLayout\s*=\s*"([a-z]+)"/g)]
    .map(match => match[2])
    .sort()
  if (layouts.length !== 2) throw new Error(`expected two page layouts, parsed ${JSON.stringify(layouts)}`)

  const templateSource = read('apps/api/app/Support/Pages/template.go')
  const islandBlock = templateSource.slice(
    templateSource.indexOf('var allowedHostIslands'),
    templateSource.indexOf('\n}\n', templateSource.indexOf('var allowedHostIslands')) + 1
  )
  const hostIslands = [...islandBlock.matchAll(/"([a-z0-9-]+)":/g)].map(match => match[1]).sort()

  return {
    schemaVersion: 1,
    views,
    layouts,
    hostIslands,
    regions: regionMatrix.regions,
    pages: pages.map(page => ({
      ...page,
      views,
      layouts,
      regions: regionsByPage.get(page.id) ?? []
    }))
  }
}

